public class Lower_UpperCase {
    public static void main(String[] args) {
        char ch;
        System.out.println("LowerCase Alphabets: ");
        for (ch=97;ch<=122;ch++){
            System.out.print(ch+" ");
        }
        System.out.println();
        System.out.println("UpperCase Alphabets: ");
        for(ch=65;ch<=90;ch++){
            System.out.print(ch+" ");
        }
    }
}
